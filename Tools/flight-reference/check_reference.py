#!/usr/bin/env python3
"""Flies the set flights of the reference model (flight.py) and compares them with the recorded results
(flight_golden.json), which the C# tests also use. It also checks the reference's ground against the heights
the plan worked out (ground_samples.json, written by Tools/world-export/gen-data.mjs).

    python3 Tools/flight-reference/check_reference.py [--write]

Run it with --write after changing flight.py on purpose: it records the new results and writes them for the
C# tests (Unity/Assets/DRONEVR/Tests/EditMode/FlightGolden.g.cs).
"""
import json, os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, HERE)
import flight

GOLD = os.path.join(HERE, 'flight_golden.json')
CS = os.path.join(ROOT, 'Unity', 'Assets', 'DRONEVR', 'Tests', 'EditMode', 'FlightGolden.g.cs')


def record():
    return {'dt': flight.DT, 'runs': [dict(r, rows=flight.fly(r)) for r in flight.RUNS]}


def write_cs(gold):
    f = lambda v: repr(float(v))
    out = ['// <auto-generated>', '// The set flights of the reference model (Tools/flight-reference/flight.py) and where the drone was, step by step.',
           '// Written by Tools/flight-reference/check_reference.py --write. Do not edit by hand.', '// </auto-generated>',
           'namespace DroneVR.Tests', '{', '    public static class FlightGolden', '    {',
           '        public static readonly string[] Names = { ' + ', '.join(json.dumps(r['name']) for r in gold['runs']) + ' };',
           '        /// <summary>For each flight: the mean wind, its gusts, where it blows from, the load in kg, the flood\'s level.</summary>',
           '        public static readonly double[][] Weather =', '        {']
    for r in gold['runs']:
        out.append('            new double[] { %s, %s, %s, %s, %s },' % (f(r['wind']), f(r['gust']), f(r['from']), f(r['payload']), f(r['level'])))
    out += ['        };', '        /// <summary>For each flight: its stretches, each as steps, forward, right, up, yaw.</summary>',
            '        public static readonly double[][][] Sticks =', '        {']
    for r in gold['runs']:
        out.append('            new[] { ' + ', '.join('new double[] { %s }' % ', '.join(f(v) for v in s) for s in r['sticks']) + ' },')
    out += ['        };', '        /// <summary>For each flight: rows of step, x, y, z, vx, vy, vz, heading, battery, landed, crash.</summary>',
            '        public static readonly double[][][] Rows =', '        {']
    for r in gold['runs']:
        out.append('            new[]')
        out.append('            {')
        for row in r['rows']:
            out.append('                new double[] { ' + ', '.join(f(v) for v in row) + ' },')
        out.append('            },')
    out += ['        };', '    }', '}', '']
    os.makedirs(os.path.dirname(CS), exist_ok=True)
    open(CS, 'w', encoding='utf-8', newline='\n').write('\n'.join(out))


new = record()
if '--write' in sys.argv:
    json.dump(new, open(GOLD, 'w'))
    write_cs(new)
    for r in new['runs']:
        last = r['rows'][-1]
        print('%-40s %5d rows, ends at (%.1f, %.1f, %.1f), battery %.0f%%, landed %d, crash %d' % (r['name'], len(r['rows']), last[1], last[2], last[3], last[8] * 100, last[9], last[10]))
    print('recorded:', os.path.relpath(GOLD, ROOT), 'and', os.path.relpath(CS, ROOT))
    sys.exit(0)

bad = 0
old = json.load(open(GOLD))
worst = 0.0
for a, b in zip(old['runs'], new['runs']):
    if len(a['rows']) != len(b['rows']):
        print('a different number of rows in:', a['name']); bad += 1; continue
    for ra, rb in zip(a['rows'], b['rows']):
        worst = max(worst, max(abs(x - y) for x, y in zip(ra, rb)))
print('largest difference from the recorded flights: %.3g' % worst)
bad += 0 if worst < 1e-9 else 1

samples = json.load(open(os.path.join(HERE, 'ground_samples.json')))
worst = max(abs(flight.ground(x, z) - h) for x, z, h in samples)
print('largest difference from the plan\'s ground, at %d points: %.3g' % (len(samples), worst))
bad += 0 if worst < 1e-9 else 1
sys.exit(1 if bad else 0)
